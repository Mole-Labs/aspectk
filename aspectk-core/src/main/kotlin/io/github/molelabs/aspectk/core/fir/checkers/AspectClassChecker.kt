package io.github.molelabs.aspectk.core.fir.checkers

import io.github.molelabs.aspectk.core.AspectKClassIds
import io.github.molelabs.aspectk.core.fir.AspectKDiagnostics
import org.jetbrains.kotlin.descriptors.ClassKind
import org.jetbrains.kotlin.diagnostics.DiagnosticReporter
import org.jetbrains.kotlin.diagnostics.reportOn
import org.jetbrains.kotlin.fir.analysis.checkers.MppCheckerKind
import org.jetbrains.kotlin.fir.analysis.checkers.context.CheckerContext
import org.jetbrains.kotlin.fir.analysis.checkers.declaration.FirRegularClassChecker
import org.jetbrains.kotlin.fir.declarations.FirRegularClass
import org.jetbrains.kotlin.fir.declarations.hasAnnotation

// Checks whether a class declared with the @Aspect annotation is an object
internal object AspectClassChecker : FirRegularClassChecker(MppCheckerKind.Common) {
    context(context: CheckerContext, reporter: DiagnosticReporter)
    override fun check(declaration: FirRegularClass) {
        if (declaration.classKind == ClassKind.OBJECT) return
        if (!declaration.hasAnnotation(AspectKClassIds.ASPECT, context.session)) return
        reporter.reportOn(declaration.source, AspectKDiagnostics.ASPECT_NOT_OBJECT, context)
    }
}
